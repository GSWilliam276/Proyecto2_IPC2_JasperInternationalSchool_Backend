package com.usac.colegio.jasperschoolbackend.transferencia;

/**
 *
 * @author eduar
 */
public class SolicitudLibro {
    private String titulo;
    private String autor;
    private String editorial;
    private Integer ejemplares;

    public SolicitudLibro() {
    }

    public String getTitulo() { return titulo; }
    public void setTitulo(String titulo) { this.titulo = titulo; }
    public String getAutor() { return autor; }
    public void setAutor(String autor) { this.autor = autor; }
    public String getEditorial() { return editorial; }
    public void setEditorial(String editorial) { this.editorial = editorial; }
    public Integer getEjemplares() { return ejemplares; }
    public void setEjemplares(Integer ejemplares) { this.ejemplares = ejemplares; }
}
